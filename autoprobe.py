def detect_project(repo: Path) -> dict:
    has = lambda *names: any((repo / n).exists() for n in names)  # noqa: E731
    python = has("pyproject.toml", "setup.py", "setup.cfg", "requirements.txt")
    info = {"python": python, "pkgs": [], "pips": [], "label": "unknown",
            "build": "cd /app/repo && ls -la"}
    nproc = '"$(nproc)"'
    if has("autogen.sh", "bootstrap", "bootstrap.sh") and not has("configure"):
        script = next(n for n in ("autogen.sh", "bootstrap", "bootstrap.sh") if has(n))
        info.update(label="autotools (bootstrap script)",
                    build=f"cd /app/repo && bash ./{script} && ./configure && make -j{nproc}")
    elif has("configure.ac", "configure.in"):
        info.update(label="autotools",
                    build=f"cd /app/repo && autoreconf -fi && ./configure && make -j{nproc}")
    elif has("configure"):
        info.update(label="configure script",
                    build=f"cd /app/repo && ./configure && make -j{nproc}")
    elif has("CMakeLists.txt"):
        info.update(label="cmake", pkgs=["cmake"],
                    build=("cd /app/repo && cmake -S . -B build -DCMAKE_BUILD_TYPE=Release "
                           f"&& cmake --build build -j{nproc}"))
    elif has("meson.build"):
        info.update(label="meson", pips=["meson", "ninja"], python=True,
                    build="cd /app/repo && meson setup build && ninja -C build")
    elif python:
        info.update(label="python",
                    build=("cd /app/repo && { [ ! -f requirements.txt ] || "
                           "pip install -r requirements.txt; } && pip install ."))
    elif has("Makefile", "makefile", "GNUmakefile"):
        info.update(label="make", build=f"cd /app/repo && make -j{nproc}")
    return info


# --------------------------------------------------------------------------
# Python import scanner (works with or without pyproject.toml)
# --------------------------------------------------------------------------
SKIP_DIRS = {".git", ".hg", ".svn", "node_modules", "build", "dist", "__pycache__",
             ".tox", "venv", ".venv", "env", ".eggs"}
# Python-2 stdlib modules: NOT pip packages, so never try to pip install them.
PY2_ONLY = {"urllib2", "urlparse", "ConfigParser", "Tkinter", "cPickle", "StringIO",
            "cStringIO", "Queue", "httplib", "commands", "__builtin__", "SocketServer",
            "HTMLParser", "tkMessageBox", "copy_reg", "xmlrpclib", "Cookie"}
IMPORT_RX = re.compile(
    r"^\s*(?:from\s+([A-Za-z_][\w.]*)\s+import\s|import\s+([A-Za-z_][\w.,\t ]*))", re.M)


def scan_python(repo: Path, max_files: int = 5000) -> dict:
    """Statically collect imports from *.py files AND extension-less scripts whose
    shebang mentions python (e.g. Examples/TimeExample/Plot).  Uses ast; files that
    don't parse (Python 2 code) fall back to a regex."""
    files: list[Path] = []
    local: set[str] = set()
    pkg_parent: dict[str, str] = {}
    for root, dirs, names in os.walk(repo):
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
        rootp = Path(root)
        has_py = False
        for n in names:
            fp = rootp / n
            if n.endswith(".py"):
                files.append(fp)
                local.add(n[:-3])
                has_py = True
                if n == "__init__.py" and rootp != repo:
                    pkg_parent[rootp.name] = str(rootp.relative_to(repo).parent)
            elif "." not in n and len(files) < max_files:
                try:
                    with fp.open("rb") as f:
                        head = f.readline(200)
                except OSError:
                    continue
                if head.startswith(b"#!") and b"python" in head:
                    files.append(fp)
                    has_py = True
        if has_py and rootp != repo:
            local.add(rootp.name)
        if len(files) >= max_files:
            break

    imports: set[str] = set()
    py2_files = 0
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        for fp in files:
            try:
                src = fp.read_text(encoding="utf-8", errors="replace")[:2_000_000]
            except OSError:
                continue
            try:
                for node in ast.walk(ast.parse(src)):
                    if isinstance(node, ast.Import):
                        imports.update(a.name.split(".")[0] for a in node.names)
                    elif isinstance(node, ast.ImportFrom) and node.level == 0 and node.module:
                        imports.add(node.module.split(".")[0])
            except (SyntaxError, ValueError):
                py2_files += 1
                for m in IMPORT_RX.finditer(src):
                    if m.group(1):
                        imports.add(m.group(1).split(".")[0])
                    else:
                        for part in m.group(2).split(","):
                            tok = part.strip().split(" ")[0].split(".")[0]
                            if tok:
                                imports.add(tok)
    imports.discard("__future__")
    third = sorted(i for i in imports if i and i not in local)
    pypath = sorted({os.path.normpath(os.path.join("/app/repo", par))
                     for name, par in pkg_parent.items() if name in imports})
    return {"files": len(files), "third_party": third, "python_path": pypath,
            "py2_files": py2_files}

# --------------------------------------------------------------------------
# Failure diagnosis (pure function -> easy to test)
# --------------------------------------------------------------------------
def command_action(tool: str):
    tool = os.path.basename(tool)
    if tool in PIP_TOOLS:
        return ("pip", tool)
    if tool in ("python", "python3", "pip", "pip3") or re.fullmatch(r"python3\.\d+", tool):
        return ("python", "")
    if tool in COMMAND_TO_PKG:
        return ("dnf", COMMAND_TO_PKG[tool])
    return ("provides", f"*/bin/{tool}")


def diagnose(text: str, pyver: str = "3.11") -> list[tuple[str, str]]:
    """Return an ordered, de-duplicated list of (kind, arg) fixes.
    kinds: dnf | provides | pip | python | pyver"""
    acts: list[tuple[str, str]] = []

    def add(kind: str, arg: str) -> None:
        if (kind, arg) not in acts:
            acts.append((kind, arg))

    lines = text.splitlines()
    tail = lines[-120:]
    blob = "\n".join(lines[-4000:])

    # 1. Explicit toolchain failures from ./configure
    for m in re.finditer(r"configure: error: (.+)", blob):
        msg = m.group(1).lower()
        if "c++ compiler" in msg:
            add("dnf", "gcc-c++")
        elif "c compiler" in msg:
            add("dnf", "gcc")
        elif "fortran" in msg:
            add("dnf", "gcc-gfortran")

    # 2. Library keywords on the error lines near the end of the log
    err_lines = [l for l in tail if ERR_LINE.search(l)]
    err_lines += [m.group(0) for m in re.finditer(r"configure: error:.*", blob)]
    for line in err_lines:
        for rx, pkg in LIB_KEYWORDS:
            if re.search(rx, line, re.I):
                add("dnf", pkg)

    # 3. Missing commands
    for m in re.finditer(r"([\w.+/-]+): (?:command )?not found", blob):
        add(*command_action(m.group(1)))
    for m in re.finditer(r"""Can't exec ["']([^"']+)["']""", blob):
        add(*command_action(m.group(1)))
    for m in re.finditer(r"""env: ['"]?([\w.+-]+)['"]?: No such file""", blob):
        add(*command_action(m.group(1)))
    for m in re.finditer(r"Unknown compiler\(s\): \[?['\"]?(\w+)", blob):
        add(*command_action(m.group(1)))
    if re.search(r"unable to find a build program corresponding to \"?Ninja", blob, re.I):
        add("pip", "ninja")

    # 4. Missing headers
    for m in re.finditer(r"([\w./+-]+\.(?:h|hpp|hh|H)):\s*No such file or directory", blob):
        hdr = m.group(1)
        if os.path.basename(hdr) == "Python.h":
            add("dnf", f"python{pyver}-devel")
        else:
            add("provides", f"*/{hdr}")

    # 5. Missing link libs
    for m in re.finditer(r"cannot find -l([\w+.-]+)", blob):
        add("provides", f"*/lib{m.group(1)}.so")

    # 6. pkg-config / meson dependencies
    for rx in (r"No package '([^']+)' found", r"Package '([^']+)', required by", r"Package '?([\w.+-]+)'? (?:was )?not found",
               r"Dependency \"([\w.+-]+)\" not found", r"Run-time dependency ([\w.+-]+) found: NO"):
        for m in re.finditer(rx, blob):
            add("provides", f"pkgconfig({m.group(1)})")

    # 7. CMake
    for m in re.finditer(r'Could not find a package configuration file provided by "([\w.+-]+)"', blob):
        add("provides", f"cmake({m.group(1)})")
    for m in re.finditer(r"CMake Error[^\n]*\n(?:[^\n]*\n){0,3}?[^\n]*Could NOT find (\w+)", blob):
        name = m.group(1).lower()
        hit = False
        for rx, pkg in LIB_KEYWORDS:
            if re.search(rx, name):
                add("dnf", pkg)
                hit = True
        if not hit:
            add("provides", f"*/lib{name}.so")

    # 8. Autoconf macros
    for m in re.finditer(r"possibly undefined macro:\s*(\w+)", blob):
        for rx, pkg in MACRO_TO_PKG:
            if re.match(rx, m.group(1)):
                add("dnf", pkg)
                break

    # 9. Python
    for m in re.finditer(r"No module named ['\"]([\w.]+)['\"]", blob):
        top = m.group(1).split(".")[0]
        add("pip", MODULE_TO_PIP.get(top, top))
    m = re.search(r"requires a different Python: [\d.]+ not in '([^']+)'", blob)
    if m:
        need = re.search(r">=\s*(\d+)\.(\d+)", m.group(1))
        if need:
            want = (int(need.group(1)), int(need.group(2)))
            for v in ("3.9", "3.11", "3.12"):
                if tuple(map(int, v.split("."))) >= want:
                    if tuple(map(int, v.split("."))) > tuple(map(int, pyver.split("."))):
                        add("pyver", v)
                    break
    if re.search(r"can't find Rust compiler|rustc.*not found|cargo.*not found", blob, re.I):
        add("dnf", "rust")
        add("dnf", "cargo")

    return acts


